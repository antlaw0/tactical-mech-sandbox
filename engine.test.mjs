import assert from 'node:assert/strict';
import * as E from './engine.js';
const g=E.newGame(12345),a=g.units[0],b=g.units[2];
assert.equal(E.distance(a,b),7);
assert.equal(E.coord(a.x,a.y),'H2');
assert.equal(E.reachable(g,a).every(p=>p.cost<=4&&!E.blocked(g,p.x,p.y)),true);
assert.equal(E.move(g,a,3,3),false);
assert.equal(E.move(g,a,1,6),true);
assert.equal(a.mp,3);
assert.equal(E.sight({x:2,y:3},{x:4,y:3}),false);
const attacker={team:'friendly',x:0,y:0,hp:100,ap:2,name:'A'};
const defender={team:'enemy',x:1,y:0,hp:50,name:'B'};
assert.ok(E.fire(attacker,defender,E.weapons[0],undefined,()=>0));
assert.equal(defender.hp,28);
assert.equal(attacker.ap,1);
E.enemyRound(g,()=>{});
assert.equal(g.round,2);
assert.equal(a.mp,4);
assert.equal(a.ap,2);
assert.equal(E.coord(4,3),'D5');
assert.deepEqual(E.sightBlockers({x:2,y:3},{x:4,y:3}).map(p=>[E.coord(p.x,p.y),p.type]),[['D4','concrete barrier']]);
const shooter={id:'a',team:'friendly',x:0,y:0,hp:100,ap:2};
const victim={id:'b',team:'enemy',x:2,y:0,hp:100};
const ally={id:'c',team:'friendly',name:'Viper',x:1,y:0,hp:80};
const testGame={units:[shooter,victim,ally]};
assert.equal(E.sightBlockers(shooter,victim,testGame)[0].type,'friendly mech Viper');
assert.equal(E.canFire(shooter,victim,E.weapons[0],testGame),false);
ally.hp=0;
assert.equal(E.canFire(shooter,victim,E.weapons[0],testGame),true);
const miss=E.fire(attacker,defender,E.weapons[0],undefined,()=>0.99);
assert.match(miss,/Miss\. Zero damage/);
assert.equal(defender.hp,28);
assert.equal(attacker.ap,0);
// Directional cover: D4 barrier is west of D5.
const covered=E.createUnit({id:'cover',name:'Cover test',team:'enemy',x:4,y:3,hp:100,max:100});
assert.equal(E.cover(covered,{x:0,y:3}),true);
assert.equal(E.cover(covered,{x:8,y:3}),false);
const unit=E.createUnit({id:'custom',name:'Custom',team:'friendly',x:0,y:0,hp:100,max:100,maxMP:7,maxAP:3,weaponIds:['laser']});
assert.equal(unit.mp,7);
assert.equal(unit.ap,3);
assert.deepEqual(E.weaponsFor(unit).map(w=>w.id),['laser']);
const enemy=E.createUnit({id:'enemy',name:'Enemy',team:'enemy',x:1,y:0,hp:80,max:80,resistances:{energy:.25},evasion:.1});
const scenario={done:false,units:[unit,enemy],random:()=>0};
const invalid=E.resolveAction(scenario,unit,{type:'attack',target:enemy,weapon:E.weapons[0]});
assert.equal(invalid.ok,false);
assert.equal(unit.ap,3);
const preview=E.attackPreview(unit,enemy,E.weapons[1],scenario);
assert.equal(preview.damage,12);
assert.equal(preview.chance,.8);
const hit=E.resolveAction(scenario,unit,{type:'attack',target:enemy,weapon:E.weapons[1]});
assert.equal(hit.hit,true);
assert.equal(hit.damage,preview.damage);
assert.equal(enemy.hp,68);
assert.equal(unit.ap,2);
const motion=E.resolveAction(scenario,unit,{type:'move',x:0,y:1});
assert.equal(motion.ok,true);
assert.equal(unit.mp,6);
// AI evaluates all targets, not only the closest one.
const ai=E.createUnit({id:'ai',name:'AI',team:'enemy',x:2,y:3,hp:90,max:90,maxMP:0,maxAP:1});
const hidden=E.createUnit({id:'hidden',name:'Hidden',team:'friendly',x:4,y:3,hp:80,max:80});
const exposed=E.createUnit({id:'exposed',name:'Exposed',team:'friendly',x:2,y:0,hp:80,max:80});
const aiGame={done:false,units:[ai,hidden,exposed]};
assert.equal(E.choosePlan(aiGame,ai).target.id,'exposed');
const rng1=E.seededRandom(42),rng2=E.seededRandom(42);
assert.deepEqual(Array.from({length:20},rng1),Array.from({length:20},rng2));
console.log('Engine combat foundation tests passed.');
