import assert from 'node:assert/strict';
import * as E from './engine.js';
const g=E.newGame(),a=g.units[0],b=g.units[2];
assert.equal(E.distance(a,b),7);
assert.equal(E.coord(a.x,a.y),'B8');
assert.equal(E.reachable(g,a).every(p=>p.cost<=4&&!E.blocked(g,p.x,p.y)),true);
assert.equal(E.move(g,a,3,3),false);
assert.equal(E.move(g,a,1,6),true);
assert.equal(a.mp,3);
assert.equal(E.sight({x:2,y:3},{x:4,y:3}),false);
const attacker={team:'friendly',x:0,y:0,hp:100,ap:2,name:'A'};
const defender={team:'enemy',x:1,y:0,hp:50,name:'B'};
assert.ok(E.fire(attacker,defender,E.weapons[0]));
assert.equal(defender.hp,28);
assert.equal(attacker.ap,1);
E.enemyRound(g,()=>{});
assert.equal(g.round,2);
assert.equal(a.mp,4);
assert.equal(a.ap,2);
console.log('Engine smoke tests passed.');
